#!/usr/bin/env node
/**
 * sync-prices — the ONLY way prices get onto the site.
 *
 * Usage:
 *   node scripts/sync-prices.mjs path/to/Elivique_Offer_Master.xlsx
 *   node scripts/sync-prices.mjs path/to/Offer_Master.csv      (CSV export of the "Offer Master" sheet)
 *
 * Writes data/packages.json. Never edit that file by hand: a price typed into a page
 * silently drifts from the rate card.
 *
 * With an .xlsx, deliverables are read from the "Deliverables" sheet.
 * With a .csv, prices update and existing deliverables in packages.json are kept.
 */
import fs from "node:fs";
import path from "node:path";
import XLSX from "xlsx";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/sync-prices.mjs <Offer_Master.xlsx | Offer_Master.csv>");
  process.exit(1);
}
const outFile = path.join(process.cwd(), "data", "packages.json");
const wb = XLSX.read(fs.readFileSync(input));

const offerSheet = wb.Sheets["Offer Master"] ?? wb.Sheets[wb.SheetNames[0]];
const rows = XLSX.utils.sheet_to_json(offerSheet, { header: 1, defval: null });
const headerIdx = rows.findIndex((r) => r[0] === "ID" && r.includes("Product"));
if (headerIdx < 0) throw new Error("Could not find the header row (ID | Division | ... ) in the Offer Master sheet.");
const header = rows[headerIdx].map((h) => String(h ?? "").trim());
const col = (name) => {
  const i = header.findIndex((h) => h.toLowerCase().startsWith(name.toLowerCase()));
  if (i < 0) throw new Error(`Column "${name}" missing from Offer Master header: ${header.join(" | ")}`);
  return i;
};
const C = {
  id: col("ID"),
  division: col("Division"),
  workstream: col("Workstream"),
  product: col("Product"),
  low: col("Price — low"),
  high: col("Price — high"),
  unit: col("Unit"),
  source: col("Rate card source"),
};

// Deliverables (xlsx only)
let deliverables = null;
if (wb.Sheets["Deliverables"]) {
  deliverables = {};
  const drows = XLSX.utils.sheet_to_json(wb.Sheets["Deliverables"], { header: 1, defval: null });
  let current = null;
  for (const r of drows.slice(1)) {
    const id = r[0] ? String(r[0]).trim() : null;
    if (id) current = id;
    const line = r[3] ? String(r[3]).trim() : "";
    if (!current || !line) continue;
    // Internal notes are never published.
    if (line.startsWith("[PROPOSED") || line.startsWith("NOTE:")) continue;
    (deliverables[current] ??= []).push(line);
  }
}

const previous = fs.existsSync(outFile) ? JSON.parse(fs.readFileSync(outFile, "utf8")) : { packages: [] };
const prevById = Object.fromEntries(previous.packages.map((p) => [p.id, p]));

const packages = [];
for (const r of rows.slice(headerIdx + 1)) {
  const id = r[C.id] ? String(r[C.id]).trim() : "";
  if (!/^[A-Z]-[A-Z0-9]+-\d+$|^X-\d+$/.test(id)) continue; // skip totals / notes rows
  const low = Number(r[C.low]);
  const high = Number(r[C.high] ?? r[C.low]);
  if (!Number.isFinite(low) || low <= 0) throw new Error(`${id}: invalid low price "${r[C.low]}"`);
  if (!Number.isFinite(high) || high < low) throw new Error(`${id}: invalid high price "${r[C.high]}"`);
  packages.push({
    id,
    division: String(r[C.division]).trim(),
    workstream: String(r[C.workstream]).trim(),
    name: String(r[C.product]).trim(),
    priceLow: low,
    priceHigh: high,
    unit: String(r[C.unit] ?? "").trim(),
    rateCardSource: String(r[C.source] ?? "").trim(),
    deliverables: deliverables ? deliverables[id] ?? [] : prevById[id]?.deliverables ?? [],
  });
}
if (packages.length === 0) throw new Error("No products found — is this the Offer Master sheet?");

const out = {
  _generated: "GENERATED by scripts/sync-prices.mjs from the Elivique Offer Master. Do not edit by hand.",
  source: path.basename(input),
  syncedAt: new Date().toISOString(),
  packages,
};
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, JSON.stringify(out, null, 2) + "\n");

// Report what changed, so a price move is never silent.
let changes = 0;
for (const p of packages) {
  const old = prevById[p.id];
  if (!old) { console.log(`+ ${p.id} ${p.name}`); changes++; continue; }
  if (old.priceLow !== p.priceLow || old.priceHigh !== p.priceHigh) {
    console.log(`~ ${p.id} ${p.name}: ${old.priceLow}–${old.priceHigh} → ${p.priceLow}–${p.priceHigh}`);
    changes++;
  }
}
for (const id of Object.keys(prevById)) if (!packages.find((p) => p.id === id)) { console.log(`- ${id} removed`); changes++; }
console.log(`Wrote ${packages.length} products to data/packages.json (${changes} change${changes === 1 ? "" : "s"}).`);
